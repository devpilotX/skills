#!/usr/bin/env python3
"""Report source files and functions that sit over their structure budget.

Measures four things per file: code lines, function length, nesting depth, and
parameter count. Defaults per language come from ../references/budgets.md and can
be overridden on the command line.

Supported extensions:
  .py .js .jsx .ts .tsx .mjs .cjs .go .java .kt .cs .rs .rb .php .c .h .cc .cpp
  .hpp .swift .sh .bash

This reads indentation and counts braces instead of parsing, so it miscounts
multi-line strings in some languages and heavily macro driven code. Treat a
finding as a reason to look at the file, not as a verdict.

Exit codes:
  0  nothing over budget
  1  at least one finding
  2  usage error

Usage:
  python3 structure_scan.py src/
  python3 structure_scan.py src/ --max-file 300 --max-function 40 --max-depth 3
  python3 structure_scan.py . --ext py,ts --json
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from dataclasses import dataclass
from pathlib import Path

# Per language budget and syntax description. "indent" languages close a block by
# returning to a lower indent column; "brace" languages close it with a brace.
